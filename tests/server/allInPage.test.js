const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const React = require('../../web/node_modules/react');
const renderer = require('../../web/node_modules/react-test-renderer');
const { MemoryRouter } = require('../../web/node_modules/react-router-dom');
const esbuild = require('../../web/node_modules/esbuild');
const file = path.resolve(__dirname, '../../web/src/pages/AllInPage.jsx');
const code = esbuild.buildSync({ entryPoints: [file], bundle: true, platform: 'node', format: 'cjs', write: false, jsx: 'automatic', external: ['react', 'react/jsx-runtime', 'react-router-dom'] }).outputFiles[0].text;
const compiled = new Module(file, module);
compiled.filename = file;
compiled.paths = Module._nodeModulePaths(path.dirname(file));
compiled._compile(code, file);
const Page = compiled.exports.default;
const { act } = renderer;
test('workspace review button brings its form into view and shows preview errors locally', async t => {
  const original = global.fetch;
  const calls = [];
  const proposal = { id: 'proposal-1', type: 'combine', confidence: 'proposed', workingName: 'Useful offering', description: 'A proposed offering', audience: 'Operators', problem: 'Repeated work', value: 'Less effort', projectIds: ['a', 'b'], reasons: [], risks: [], steps: [], successCriteria: [], evidence: [] };
  const report = { id: 'report-1', summary: 'A portfolio direction', createdAt: new Date().toISOString(), coverage: { total: 2, assessed: 2, described: 2, byLens: {} }, gaps: [], sourceProjects: [{id:'a',name:'Alpha'}, {id:'b',name:'Beta'}], recommendations: [proposal] };
  global.fetch = async url => ({ ok: url !== '/api/workspaces/preview', status: url === '/api/workspaces/preview' ? 409 : 200, json: async () => url === '/api/all-in' ? {currentReport:report,history:[]} : url === '/api/settings' ? {} : url === '/api/workspaces/preview' ? {message:'A source assessment changed; refresh All In'} : [] });
  let root;
  t.after(() => { if(root) act(() => root.unmount()); global.fetch = original; });
  await act(async () => { root = renderer.create(React.createElement(MemoryRouter, {future:{v7_startTransition:true,v7_relativeSplatPath:true}}, React.createElement(Page)), {createNodeMock: element => element.props.className === 'card workspace-review' ? { scrollIntoView: () => calls.push('scroll'), focus: () => calls.push('focus') } : null}); });
  const button = text => root.root.findAllByType('button').find(b => b.children.join('').includes(text));
  await act(async () => button('Review linked workspace').props.onClick());
  assert.deepEqual(calls, ['scroll', 'focus']);
  const form = root.root.findByProps({className:'card workspace-review'});
  assert.equal(form.props.tabIndex, -1);
  await act(async () => button('Preview exact folders').props.onClick());
  assert.ok(form.findAllByProps({role:'alert'}).some(n => n.children.join('').includes('source assessment changed')));
});
